//! Watches the clipboard for newly copied text and tells the widget ("clip" event).
//!
//! * Text only. Images and files are ignored.
//! * Anything a password manager marks as private is skipped: on Windows the
//!   standard "don't record this" clipboard formats, on macOS the
//!   org.nspasteboard concealed / transient types.
//! * While paused it doesn't read the clipboard at all, and things copied
//!   during the pause are not picked up afterwards.

use std::sync::atomic::{AtomicBool, Ordering};
use std::thread;
use std::time::Duration;

use tauri::{AppHandle, Emitter};

static PAUSED: AtomicBool = AtomicBool::new(false);
/// Dot Deck: only watch while the Clipboard widget is on (treated like a pause).
pub static ENABLED: AtomicBool = AtomicBool::new(false);
static STARTED: AtomicBool = AtomicBool::new(false);
const MAX_LEN: usize = 20_000;

/// Starts the watcher the first time the Clipboard widget is switched on.
pub fn start(app: AppHandle) {
    if STARTED.swap(true, Ordering::SeqCst) {
        return;
    }
    thread::spawn(move || {
        let mut cb = loop {
            match arboard::Clipboard::new() {
                Ok(c) => break c,
                Err(_) => thread::sleep(Duration::from_secs(2)),
            }
        };
        // Whatever is on the clipboard at start-up isn't "new".
        let mut last = cb.get_text().unwrap_or_default();
        let mut was_paused = false;
        loop {
            thread::sleep(Duration::from_millis(500));
            if PAUSED.load(Ordering::SeqCst) || !ENABLED.load(Ordering::SeqCst) {
                was_paused = true;
                continue;
            }
            let text = match cb.get_text() {
                Ok(t) => t,
                Err(_) => continue, // empty, an image, or busy
            };
            if was_paused {
                was_paused = false;
                last = text;
                continue;
            }
            if text == last {
                continue;
            }
            last = text.clone();
            if text.trim().is_empty() || text.len() > MAX_LEN || private() {
                continue;
            }
            let _ = app.emit("clip:clipboard", text);
        }
    });
}

/// True when the app that copied asked for it not to be recorded (password managers do).
#[cfg(windows)]
fn private() -> bool {
    use windows_sys::Win32::System::DataExchange::{IsClipboardFormatAvailable, RegisterClipboardFormatW};
    for name in ["ExcludeClipboardContentFromMonitorProcessing", "CanIncludeInClipboardHistory", "Clipboard Viewer Ignore"] {
        let wide: Vec<u16> = name.encode_utf16().chain(std::iter::once(0)).collect();
        unsafe {
            let format = RegisterClipboardFormatW(wide.as_ptr());
            if format != 0 && IsClipboardFormatAvailable(format) != 0 {
                return true;
            }
        }
    }
    false
}

#[cfg(target_os = "macos")]
fn private() -> bool {
    let script = "ObjC.import('AppKit'); var t = $.NSPasteboard.generalPasteboard.types; var a = []; \
                  for (var i = 0; i < t.count; i++) a.push(ObjC.unwrap(t.objectAtIndex(i))); a.join('\\n')";
    match std::process::Command::new("/usr/bin/osascript").args(["-l", "JavaScript", "-e", script]).output() {
        Ok(o) => {
            let types = String::from_utf8_lossy(&o.stdout);
            types.contains("org.nspasteboard.ConcealedType")
                || types.contains("org.nspasteboard.TransientType")
                || types.contains("org.nspasteboard.AutoGeneratedType")
                || types.contains("com.agilebits.onepassword")
        }
        Err(_) => false,
    }
}

#[cfg(not(any(windows, target_os = "macos")))]
fn private() -> bool {
    false
}

/// Puts text back on the clipboard (clicking an item on the widget).
#[tauri::command]
pub fn copy_clip(text: String) -> Result<(), String> {
    arboard::Clipboard::new()
        .and_then(|mut c| c.set_text(text))
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub fn set_paused(paused: bool) {
    PAUSED.store(paused, Ordering::SeqCst);
}
